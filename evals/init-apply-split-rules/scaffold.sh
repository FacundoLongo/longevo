#!/usr/bin/env bash
# A repo whose rules are split three ways: AGENTS.md says pnpm, CLAUDE.md says npm and has a rule of its own
# (no @AGENTS.md import), and a Cursor rule has another rule of its own. The lockfile shows pnpm is right.
set -euo pipefail
mkdir -p src/generated .cursor/rules
cat > package.json <<'JSON'
{ "name": "shop", "private": true, "type": "module", "scripts": { "test": "vitest run", "build": "tsc" }, "devDependencies": { "vitest": "^3.2.0", "typescript": "^5.6.0" } }
JSON
printf "lockfileVersion: '9.0'\n" > pnpm-lock.yaml
cat > AGENTS.md <<'MD'
# Rules

- Use pnpm.
- Run `pnpm test` before you push.
MD
cat > CLAUDE.md <<'MD'
# Claude

- Use npm.
- Never edit files in src/generated/.
MD
cat > .cursor/rules/style.mdc <<'MD'
---
alwaysApply: true
---
- Use named exports only.
MD
cat > src/cart.ts <<'TS'
export function total(items: { price: number; qty: number }[]): number {
  return items.reduce((sum, item) => sum + item.price * item.qty, 0);
}
TS
cat > src/cart.test.ts <<'TS'
import { expect, test } from 'vitest';
import { total } from './cart';

test('adds price times quantity', () => {
  expect(total([{ price: 2, qty: 3 }, { price: 1, qty: 1 }])).toBe(7);
});
TS
printf '// Generated by the API client. Do not edit.\nexport const api = {};\n' > src/generated/api.ts
git init -q && git add -A && git -c user.email=eval@example.com -c user.name=eval commit -qm init
