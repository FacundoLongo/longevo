// docs/coverage.md: tests and docs by area, and rules when there are any (D8). Same input, same output.
import { join } from 'node:path';
import { isNoise } from './attributes.mjs';
import { livingDocs } from './docs.mjs';
import { matchesAny } from './glob.mjs';
import { findRules } from './rules.mjs';
import { analyzeTests, areaOf, isTestFile } from './tests.mjs';
import { readText } from './text.mjs';
import { workspaces } from './workspaces.mjs';

export { testKind } from './tests.mjs';
export const COVERAGE_FILE = 'docs/coverage.md';
export const CODE_FILE = /\.(ts|tsx|js|jsx|mjs|cjs|go|py|rb|rs|swift|kt|kts|java|cs|php|ex|exs|dart|scala|c|cc|cpp|h|hpp|m|mm|vue|svelte)$/;

const cell = (text) => String(text).replace(/\|/g, '\\|');
const row = (cells) => `|${cells.map((c) => (c === '' ? ' ' : ` ${cell(c)} `)).join('|')}|`;
const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// Rules keep their Code line as [{ path, start, end }]; older callers pass a string.
const codeRefs = (code) => {
  if (!Array.isArray(code)) return code ?? '';
  return code.map(({ path, start, end }) => (start ? `${path}:${start}${end && end !== start ? `-${end}` : ''}` : path)).join(', ');
};

export function renderCoverage({ files, packages, tests, docs, rules = [] }) {
  const out = ['# Coverage', '', 'Generated by Longevo. Do not edit by hand: run the `longevo-init` skill to update it.', '', '## Tests by area', ''];
  const areas = new Map();
  for (const test of tests) {
    const counts = areas.get(test.area) ?? { total: 0, e2e: 0, integration: 0, other: 0, mocks: 0 };
    counts.total += 1;
    counts[test.kind] += 1;
    if (test.mocksStorage) counts.mocks += 1;
    areas.set(test.area, counts);
  }
  if (areas.size === 0) {
    out.push('No test files found.');
  } else {
    out.push('| Area | Test files | End to end | Integration | Other | Mock storage |', '| --- | --- | --- | --- | --- | --- |');
    for (const area of [...areas.keys()].sort(byText)) {
      const c = areas.get(area);
      out.push(row([area, c.total, c.e2e, c.integration, c.other, c.mocks]));
    }
  }
  out.push('', '## Docs by area', '');
  const codeByArea = new Map();
  for (const file of files.filter((f) => CODE_FILE.test(f) && !isTestFile(f))) {
    const area = areaOf(file, packages);
    if (!codeByArea.has(area)) codeByArea.set(area, []);
    codeByArea.get(area).push(file);
  }
  if (codeByArea.size === 0) {
    out.push('No code files found.');
  } else {
    out.push('| Area | Docs | Verified |', '| --- | --- | --- |');
    for (const area of [...codeByArea.keys()].sort(byText)) {
      const covering = docs.filter((doc) => codeByArea.get(area).some((file) => matchesAny(file, doc.covers))).sort((a, b) => byText(a.path, b.path));
      const dates = covering.map((doc) => doc.verified && String(doc.verified).slice(0, 10)).filter(Boolean).sort(byText);
      out.push(row([area, covering.length ? covering.map((doc) => doc.path).join(', ') : 'none', dates[0] ?? '']));
    }
  }
  if (rules.length) {
    out.push('', '## Rules', '', '| Rule | Status | Code | Test |', '| --- | --- | --- | --- |');
    for (const rule of [...rules].sort((a, b) => byText(a.id, b.id))) out.push(row([`${rule.id} ${rule.title}`, rule.status ?? '', codeRefs(rule.code), rule.test ?? '']));
  }
  out.push('');
  return out.join('\n');
}

// Renders the record for the whole repo. `docs` and `rules` can be passed when the caller already has them.
export function coverageFor(sc, files, generated, { docs, rules = findRules(sc, files) } = {}) {
  const clean = files.filter((file) => !isNoise(file, generated));
  const { packages } = workspaces(sc.root, files);
  const living = docs ?? livingDocs(sc, files, generated, { drift: false }).living;
  return renderCoverage({ files: clean, packages, tests: analyzeTests(sc.root, clean, packages), docs: living, rules });
}

export function coverageState(root, rendered) {
  const current = readText(join(root, COVERAGE_FILE));
  return { file: COVERAGE_FILE, exists: current !== null, upToDate: current === rendered };
}
