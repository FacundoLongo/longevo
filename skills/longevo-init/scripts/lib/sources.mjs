// External sources listed in each doc's frontmatter, and docs/sources.md generated from them.
// Whether a source changed at the origin is checked by sync through MCP and never stored.
import { join } from 'node:path';
import { realDate } from './dates.mjs';
import { parseFrontmatter } from './frontmatter.mjs';
import { readText } from './text.mjs';

export const SOURCES_FILE = 'docs/sources.md';
export const SOURCE_MAX_AGE_DAYS = 30;

const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const cell = (text) => String(text).replace(/\|/g, '\\|');
const daysBetween = (from, to) => (Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86_400_000;

export function collectSources(sc, files) {
  const byUrl = new Map();
  for (const doc of files.filter((file) => /\.mdx?$/.test(file) && !/(^|\/)node_modules\//.test(file)).sort()) {
    const text = readText(join(sc.root, doc));
    if (text === null || !/^sources:/m.test(text)) continue;
    const { data } = parseFrontmatter(text);
    for (const raw of Array.isArray(data.sources) ? data.sources : []) {
      const entry = typeof raw === 'string' ? { url: raw } : raw;
      if (!entry?.url) continue;
      const source = byUrl.get(entry.url) ?? { url: entry.url, title: null, citedBy: [], checked: undefined };
      source.title = source.title ?? entry.title ?? null;
      source.citedBy.push(doc);
      const checked = entry.checked ?? null;
      // The oldest check wins: a source is only as fresh as the doc that checked it last.
      source.checked = source.checked === undefined ? checked : source.checked === null || checked === null ? null : [source.checked, checked].sort(byText)[0];
      byUrl.set(entry.url, source);
    }
  }
  return [...byUrl.values()].sort((a, b) => byText(a.url, b.url));
}

const readable = realDate;

export function sourceFindings(sources, today) {
  return sources
    .filter((source) => !readable(source.checked) || daysBetween(source.checked.slice(0, 10), today) > SOURCE_MAX_AGE_DAYS)
    .map((source) => ({
      id: 'source-not-checked',
      severity: 'medium',
      evidence: [source.url],
      docs: source.citedBy,
      message: readable(source.checked) ? `${source.url} was last checked on ${source.checked}.` : `${source.url} has no checked date Longevo can read.`,
    }));
}

export function renderSources(sources) {
  const out = ['# Sources', '', "Generated by Longevo from the `sources` in each doc's frontmatter. Do not edit by hand: run the `longevo-sync` skill to update it.", ''];
  if (sources.length === 0) {
    out.push('No doc lists a source yet.');
  } else {
    out.push('| Source | Cited by | Checked |', '| --- | --- | --- |');
    for (const source of [...sources].sort((a, b) => byText(a.url, b.url))) {
      const label = source.title ? `${source.title} (${source.url})` : source.url;
      out.push(`| ${cell(label)} | ${cell([...source.citedBy].sort(byText).join(', '))} |${source.checked ? ` ${source.checked} ` : ' '}|`);
    }
  }
  out.push('');
  return out.join('\n');
}
