import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderCoverage } from '../src/lib/coverage.mjs';
import { testKind } from '../src/lib/tests.mjs';
import { scan } from '../src/scan.mjs';
import { makeRepo } from './helpers/fixture.mjs';

test('classifies tests by path and name markers', () => {
  assert.equal(testKind('e2e/login.spec.ts'), 'e2e');
  assert.equal(testKind('web/cypress/a.cy.ts'), 'e2e');
  assert.equal(testKind('src/orders.e2e.test.ts'), 'e2e');
  assert.equal(testKind('tests/integration/test_db.py'), 'integration');
  assert.equal(testKind('store/pg_integration_test.go'), 'integration');
  assert.equal(testKind('src/test/java/OrderRepositoryIT.java'), 'integration');
  assert.equal(testKind('src/test/java/UnitTest.java'), 'other');
  assert.equal(testKind('src/cart.test.ts'), 'other');
});

test('renders tests and docs by area, sorted, with no timestamps', () => {
  const md = renderCoverage({
    files: ['packages/web/src/b.ts', 'packages/api/src/a.ts', 'packages/api/src/a.test.ts', 'packages/api/tests/integration/db.test.ts'],
    packages: ['packages/api', 'packages/web'],
    tests: [
      { file: 'packages/api/src/a.test.ts', area: 'packages/api', kind: 'other', mocksStorage: true },
      { file: 'packages/api/tests/integration/db.test.ts', area: 'packages/api', kind: 'integration', mocksStorage: false },
    ],
    docs: [{ path: 'docs/api.md', covers: ['packages/api/**'], verified: '2026-10-11' }],
  });
  assert.equal(md, [
    '# Coverage',
    '',
    'Generated by Longevo. Do not edit by hand: run the `longevo-init` or `longevo-sync` skill to update it.',
    '',
    '## Tests by area',
    '',
    '| Area | Test files | End to end | Integration | Other | Mock storage |',
    '| --- | --- | --- | --- | --- | --- |',
    '| packages/api | 2 | 0 | 1 | 1 | 1 |',
    '',
    '## Docs by area',
    '',
    '| Area | Docs | Verified |',
    '| --- | --- | --- |',
    '| packages/api | docs/api.md | 2026-10-11 |',
    '| packages/web | none | |',
    '',
  ].join('\n'));
});

test('says so when there are no tests, and adds rules when there are any', () => {
  const md = renderCoverage({
    files: ['src/a.go'],
    packages: [],
    tests: [],
    docs: [],
    rules: [{ id: 'R-PAY-001', title: 'No double charge', status: 'implemented and tested', code: [{ path: 'src/a.go', start: 10, end: 10 }], test: 'ignores a repeated event' }],
  });
  assert.match(md, /## Tests by area\n\nNo test files found\.\n/);
  assert.match(md, /\| R-PAY-001 No double charge \| implemented and tested \| src\/a\.go:10 \| ignores a repeated event \|/);
});

test('the same input gives the same output', () => {
  const input = { files: ['b/x.py', 'a/y.py'], packages: [], tests: [], docs: [] };
  assert.equal(renderCoverage(input), renderCoverage({ ...input, files: [...input.files].reverse() }));
});

test('the scan says when docs/coverage.md is missing or out of date', () => {
  const root = makeRepo({ 'src/a.ts': '1', 'src/a.test.ts': 'test()', 'docs/coverage.md': '# Coverage\nold\n' });
  const { hash, ...state } = scan(root, { home: root }).coverage;
  assert.deepEqual(state, { file: 'docs/coverage.md', exists: true, upToDate: false });
  assert.match(hash, /^[0-9a-f]{12}$/);
  const { hash: _, ...missing } = scan(makeRepo({ 'a.ts': '1' }), { home: root }).coverage;
  assert.deepEqual(missing, { file: 'docs/coverage.md', exists: false, upToDate: false });
});

test('the CLI prints the record', async () => {
  const { spawnSync } = await import('node:child_process');
  const cli = new URL('../src/longevo.mjs', import.meta.url).pathname;
  const root = makeRepo({ 'src/a.ts': '1', 'src/a.test.ts': 'test()' });
  const result = spawnSync(process.execPath, [cli, 'coverage', '--cwd', root], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stdout);
  assert.match(result.stdout, /^# Coverage\n[\s\S]*\| src \| 1 \| 0 \| 0 \| 1 \| 0 \|/);
});

test('an area with only tests gets no docs row', () => {
  const md = renderCoverage({ files: ['tests/x.test.ts', 'src/a.ts'], packages: [], tests: [], docs: [] });
  assert.match(md, /\| src \| none \| \|/);
  assert.doesNotMatch(md, /\| tests \| none/);
});

test('a mock written inside a string is test data, not a mock', async () => {
  const { analyzeTests } = await import('../src/lib/tests.mjs');
  const root = makeRepo({
    'a.test.ts': "vi.mock('../db')\ntest('x', () => {})\n",
    'b.test.ts': "const fixture = { 'b.test.ts': \"vi.mock('../db')\" };\nconst header = '| Mock storage |';\n",
  });
  const rows = Object.fromEntries(analyzeTests(root, ['a.test.ts', 'b.test.ts']).map((row) => [row.file, row.mocksStorage]));
  assert.deepEqual(rows, { 'a.test.ts': true, 'b.test.ts': false });
});

test('the coverage record lists the rules found in docs', async () => {
  const { coverageFor } = await import('../src/lib/coverage.mjs');
  const { scope, listFiles } = await import('../src/lib/repo.mjs');
  const root = makeRepo({
    'docs/domain/pay.md': '### R-PAY-001 · No double charge\nCode: src/a.ts:1, src/b.ts:2-4\nTest: "x"\nStatus: implemented and tested\n',
    'src/a.ts': '1\n',
    'src/b.ts': '1\n2\n3\n4\n',
  });
  const sc = scope(root);
  assert.match(coverageFor(sc, listFiles(sc).files, new Set()), /\| R-PAY-001 No double charge \| implemented and tested \| src\/a\.ts:1, src\/b\.ts:2-4 \| x \|/);
});

test('the coverage state carries a hash of the record it would write, for decline keys', async () => {
  const { coverageState } = await import('../src/lib/coverage.mjs');
  const root = makeRepo({ 'a.md': '# A\n' });
  const one = coverageState(root, '# Coverage\n\none\n');
  assert.match(one.hash, /^[0-9a-f]{12}$/);
  assert.equal(coverageState(root, '# Coverage\n\none\n').hash, one.hash);
  assert.notEqual(coverageState(root, '# Coverage\n\ntwo\n').hash, one.hash);
});
