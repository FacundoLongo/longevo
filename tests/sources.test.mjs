import { test } from 'node:test';
import assert from 'node:assert/strict';
import { apply } from '../src/lib/apply.mjs';
import { collectSources, renderSources, sourceFindings } from '../src/lib/sources.mjs';
import { briefs } from '../src/lib/work.mjs';
import { scope } from '../src/lib/repo.mjs';
import { gitIn, makeRepo } from './helpers/fixture.mjs';

const listed = (root) => gitIn(root, 'ls-files').split('\n').filter(Boolean);
const DOCS = {
  'docs/domain/pay.md': '---\ncovers: ["src/**"]\nsources:\n  - url: https://linear.app/t/1\n    checked: 2026-10-01\n  - url: https://notion.so/billing\n    checked: 2026-08-01\n---\n# Pay\n',
  'docs/domain/refund.md': '---\nsources:\n  - url: https://notion.so/billing\n    title: Billing policy\n    checked: 2026-09-20\n---\n# Refund\n',
  'src/a.ts': '1',
};

test('collects each source once with the docs that cite it and the oldest check', () => {
  const root = makeRepo(DOCS);
  assert.deepEqual(collectSources(scope(root), listed(root)), [
    { url: 'https://linear.app/t/1', title: null, citedBy: ['docs/domain/pay.md'], checked: '2026-10-01' },
    { url: 'https://notion.so/billing', title: 'Billing policy', citedBy: ['docs/domain/pay.md', 'docs/domain/refund.md'], checked: '2026-08-01' },
  ]);
});

test('accepts a plain list of links', () => {
  const root = makeRepo({ 'docs/a.md': '---\nsources: ["https://x.io/a"]\n---\n' });
  assert.deepEqual(collectSources(scope(root), listed(root)), [{ url: 'https://x.io/a', title: null, citedBy: ['docs/a.md'], checked: null }]);
});

test('a source is old after 30 days', () => {
  const sources = [{ url: 'a', citedBy: ['d'], checked: '2026-09-11' }, { url: 'b', citedBy: ['d'], checked: '2026-09-12' }, { url: 'c', citedBy: ['d'], checked: null }];
  assert.deepEqual(sourceFindings(sources, '2026-10-12').map((f) => f.evidence[0]), ['a', 'c']);
});

test('the same docs give the same file', () => {
  const root = makeRepo(DOCS);
  const sources = collectSources(scope(root), listed(root));
  const md = renderSources(sources);
  assert.equal(md, renderSources([...sources].reverse()));
  assert.equal(md, [
    '# Sources',
    '',
    "Generated by Longevo from the `sources` in each doc's frontmatter. Do not edit by hand: run the `longevo-sync` skill to update it.",
    '',
    '| Source | Cited by | Checked |',
    '| --- | --- | --- |',
    '| https://linear.app/t/1 | docs/domain/pay.md | 2026-10-01 |',
    '| Billing policy (https://notion.so/billing) | docs/domain/pay.md, docs/domain/refund.md | 2026-08-01 |',
    '',
  ].join('\n'));
});

test('says so when no doc has sources', () => {
  assert.match(renderSources([]), /No doc lists a source yet\./);
});

test('lists briefs with their status', () => {
  const root = makeRepo({ 'docs/work/2026-10-01-refunds/brief.md': '---\nstatus: done\ntask: https://linear.app/t/9\ncovers: ["src/refunds/**"]\n---\n# Brief\n' });
  assert.deepEqual(briefs(scope(root), listed(root)), [{ path: 'docs/work/2026-10-01-refunds/brief.md', status: 'done', task: 'https://linear.app/t/9', covers: ['src/refunds/**'] }]);
});

test('checked needs a url, and dates Longevo cannot read count as old', () => {
  const root = makeRepo({ 'docs/a.md': '---\nsources:\n  - title: No link\n    checked: 2026-01-01\n---\n' });
  assert.throws(() => apply('checked', root, { doc: 'docs/a.md' }), /url/);
  const found = sourceFindings([{ url: 'a', citedBy: ['d'], checked: 'last week' }, { url: 'b', citedBy: ['d'], checked: '2026/01/01' }], '2026-10-11');
  assert.deepEqual(found.map((f) => f.evidence[0]), ['a', 'b']);
});
